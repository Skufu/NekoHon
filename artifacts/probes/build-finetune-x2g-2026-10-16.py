def passages_of(user):
    body = user.split("Passages:", 1)[1]
    parts = PASSAGE_SPLIT.split(body)
    out = []
    for i in range(1, len(parts), 3):
        chapter, chunk_id, text = parts[i], parts[i + 1], parts[i + 2]
        out.append({
            "chapter": chapter.strip(),
            "chunk_id": chunk_id,
            "text": text.split("\n\nQuestion:")[0].rstrip(),
        })
    return out


def norm_tokens(text):
    return set(TOKEN_RE.findall(text.lower()))


def normalized(text):
    return " ".join(TOKEN_RE.findall(text.lower()))


def similarity(text_a, text_b):
    ratio = difflib.SequenceMatcher(None, normalized(text_a), normalized(text_b)).ratio()
    set_a, set_b = norm_tokens(text_a), norm_tokens(text_b)
    union = set_a | set_b
    jaccard = len(set_a & set_b) / len(union) if union else 0.0
    return ratio, jaccard


def generate_live_gloss(selection, sentence):
    payload = json.dumps({
        "model": "qwen2.5:7b",
        "messages": [
            {"role": "system", "content": EXPLAIN_GLOSS_SYSTEM},
            {"role": "user", "content": f"Highlighted text: {selection}\nSentence containing highlight: {sentence}\nExplain in 1 plain sentence what the highlighted text means in this context."}
        ],
        "stream": False,
        "options": {"temperature": 0.0}
    }).encode("utf-8")
    req = urllib.request.Request(
        "http://127.0.0.1:11434/api/chat",
        data=payload,
        headers={"Content-Type": "application/json"}
    )
    with urllib.request.urlopen(req, timeout=60) as resp:
        ans = json.loads(resp.read().decode())["message"]["content"].strip()
    ans = re.sub(r"\[Ch\.[^\]]*\]", "", ans).replace('"', "").replace("\n", " ").strip()
    if not ans.endswith("."):
        ans += "."
    return ans



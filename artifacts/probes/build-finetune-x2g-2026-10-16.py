    # -------------------------------------------------------------------------
    # Layer 4: Balanced Refusals (54 from x2d + 18 distinct from x2e new-refusals)
    # -------------------------------------------------------------------------
    x2d_ref = [json.loads(json.dumps(r)) for r in x2d if r["messages"][2]["content"] == "Not in this book."]
